// 🔴 العمودُ حمل في الإنتاج **أربعَ** قيمٍ لمعنيَين: MALE ٥٦٥ · FEMALE ١٢٤ ·
//    male ٧٧ · female ٧. والواجهاتُ تقارن `=== 'FEMALE'` حرفيّاً في ثمانية
//    مواضع، فسبعُ لاعباتٍ كنّ يظهرن «ذكر» في صفحة اللاعبين وصفحة اللاعب
//    والمستكشف — ويُبنى على ذلك قرارُ الإجلاس والأدوارُ المؤنّثة.
//
// 🔴 والإصلاحُ في الخادم لا في مواضع العرض الثمانية: تصحيحُ العرض يترك
//    العمودَ يستقبل قيمةً خامسةً يومَ يكتب فيه مسارٌ جديد، ويُلزم كلَّ
//    مستهلكٍ قادمٍ أن يعرف الفخَّ ويتذكّره.
// ══════════════════════════════════════════════════════

export type Gender = 'MALE' | 'FEMALE';

/**
 * يُرجع القيمةَ القياسيّة لأيّ مدخل.
 *
 * الافتراضُ `MALE` لأنّه افتراضُ الإنشاء القائم في `createPlayer` — تغييرُه
 * هنا كان سيقلب جنسَ كلّ صفٍّ فارغٍ صامتاً.
 */
export function normGender(g: unknown): Gender {
  return String(g ?? '').trim().toUpperCase() === 'FEMALE' ? 'FEMALE' : 'MALE';
}

/** هل القيمةُ أنثى — للقراءة، يحتمل أيَّ حالةِ أحرف */
export function isFemale(g: unknown): boolean {
  return normGender(g) === 'FEMALE';
}
