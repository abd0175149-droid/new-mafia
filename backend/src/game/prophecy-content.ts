/** أسبوعُ الموسم (١..١٣) من تاريخ بدئه — بلا موسمٍ نشط (مسودّة/تجربة) الأسبوع الأوّل */
export function seasonWeek(startedAt: Date | string | null | undefined, now = Date.now()): number {
  if (!startedAt) return 1;
  const days = Math.floor((now - new Date(startedAt).getTime()) / 86400000);
  return Math.min(13, Math.max(1, Math.floor(days / 7) + 1));
}

/** سطرُ القلب — في غرفة الموسم وحدها */
export function flipLineFor(state: any, role: string | null | undefined): string | null {
  if (!state?.config?.prophecy || !role) return null;
  return FLIP_LINES[role] || null;
}

