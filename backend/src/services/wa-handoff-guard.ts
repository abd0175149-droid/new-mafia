// ══════════════════════════════════════════════════════
// 🛡️ حارس «الوعد بالتحويل» — هل قال البوت للعميل إنّه حوّله للإدارة؟
// ══════════════════════════════════════════════════════
// النموذج يكتب «حوّلتك للإدارة» أو «وصلتك الإدارة» دون أن يستدعي handoff_to_human،
// فلا تصل الإدارةَ إشارةٌ ولا تظهر شارة «بحاجة تدخّل» — والعميل ينتظر وعداً لن يُنفَّذ.
// (عاصم #442، 2026-09-29: ثلاث وعود في خمس دقائق لم يصل منها شيء؛ وبشّار #400 قبلها.)
// فإن وجد هذا الحارسُ وعداً في الردّ ولم يُستدعَ التحويل، تُحوِّل الشيفرةُ بنفسها.
//
// المعيار جملةً جملة: وعدٌ = فعلُ تحويلٍ/تبليغ + ذكرُ الإدارة/موظّف، في جملةٍ ليست
// سؤالاً ولا عرضاً مشروطاً («إذا بتحب أحوّلك؟» عرضٌ لا وعد) ولا نفياً.
// ══════════════════════════════════════════════════════

// «إدار» بلا «ال»: «للإدارة» = ل+ل+إدارة لا تحوي «الإدار»
const STAFF = /(إدار|ادار|موظف|موظّف|إنسان|انسان|بشري|بشريّ|المسؤول|المسئول|المدير)/;

/** كلماتُ العرض والشرط — كلمةً كاملة (لا تُطابَق داخل «ممكنة» مثلاً) */
const OFFER_WORDS = new Set([
  'إذا', 'اذا', 'إذا', 'لو', 'حابب', 'حابّ', 'حابة', 'حابّة', 'بتحب', 'بتحبّ', 'تحب', 'تحبّ', 'بدك', 'بدّك', 'تريد', 'بتريد',
  'ودّك', 'ودك', 'بقدر', 'بنقدر', 'منقدر', 'ممكن', 'بإمكاني', 'بامكاني', 'يمكنني', 'أقدر', 'اقدر', 'بتفضّل', 'بتفضل', 'تفضّل',
]);

const CLAIMS: RegExp[] = [
  /حوّ?لتك|حوّ?لت\s*(طلبك|محادثتك|موضوعك|رسالتك)/,                       // حوّلتك / حوّلت طلبك
  /تم+\s+(تحويل|إرسال|ارسال|رفع|إبلاغ|ابلاغ|تبليغ)/,                        // تمّ تحويل طلبك
  /(أشّ?رت|اشّ?رت|نبّ?هت|بلّ?غت|أبلغت|ابلغت)\s+(لل|ل)?(إدار|ادار|الإدار|الادار)/, // بلّغت الإدارة
  /[أا]حوّ?لك/,                                                            // خليني أحوّلك / أحوّلك لإنسان
  /(رح|راح|سوف)\s+(يتواصلوا|يتواصل|تتواصل|يكلموك|يكلّموك|يحكوا\s+معك|يحكو\s+معك|يردّوا|يردوا|يتابعوا\s+معك|يتابع\s+معك)/,
  /(سيتواصلون|سيتواصل|ستتواصل)/,
  // «لحظة واحدة وبتكون مع الإدارة» (تامر #531، 2026-10-01): أنت ستكون مع الإدارة
  /(بت|رح\s*ت|راح\s*ت|حت|ست)كون\s+مع\s+(ال)?(إدار|ادار|موظف|موظّف)/,
  // «ثواني ويكونوا معك من الإدارة» — بقرينة استعجال، لا «الليدر من الإدارة بيكون معكم طول السهرة»
  /(لحظ|ثوان|ثواني|ثانية|دقيقة|حالاً|حالا|فوراً|فورا|هلأ|هلق|هسا|هسّا)[^.!؟?\n]*(ي|بي|رح\s*ي|راح\s*ي)كون(وا|و)?\s+معك(?!م)/,
];
// «وصل طلبك للإدارة» هي خاتمةُ تأكيد الحجز المعتادة (= سُجّل حجزك) — وعدٌ بالتحويل في غيره فقط
const DELIVERY_CLAIMS: RegExp[] = [
  /وصّ?لت(ك)?\s+(لل|ل)?(إدار|ادار|الإدار|الادار)/,                          // وصلتك الإدارة
  /وصّ?ل\s+طلبك/,                                                          // وصل طلبك للإدارة
];
const BOOKING_DONE = /تمّ?\s+((تثبيت|تأكيد|تاكيد)\s+)?حج[ْ]?زك|حجزك\s+(ثابت|مثبّت|مثبت|تثبّت|تأكّد|تأكد)|انحجز(لك)?/;

const NEGATED = /(^|\s)(ما|مش|لن|مو)\s+(رح\s+|راح\s+|بقدر\s+)?[أا]?حوّ?ل/;

function words(s: string): string[] {
  return s.split(/[\s،,:;«»"()]+/).filter(Boolean).map(w => w.replace(/^[وف](?=[إاأ])/, ''));
}

/**
 * هل في الردّ جملةٌ تعِد العميل بأنّه حُوِّل للإدارة (أو ستتواصل معه الآن)؟
 * `booking`: الدورُ ثبّت حجزاً (create_reservation) — فـ«وصل طلبك للإدارة» تأكيدُ حجزٍ لا تحويل.
 */
export function claimsHandoff(text: string, ctx: { booking?: boolean } = {}): boolean {
  const t = String(text || '');
  const booking = !!ctx.booking || BOOKING_DONE.test(t);
  const patterns = booking ? CLAIMS : [...CLAIMS, ...DELIVERY_CLAIMS];
  for (const m of t.matchAll(/[^.!؟?\n]+[.!؟?\n]*/g)) {
    const s = m[0];
    if (/[؟?]/.test(s)) continue;                       // سؤالٌ لا وعد
    if (!STAFF.test(s)) continue;
    if (NEGATED.test(s)) continue;
    if (words(s).some(w => OFFER_WORDS.has(w))) continue; // عرضٌ مشروط
    if (patterns.some(r => r.test(s))) return true;
  }
  return false;
}
