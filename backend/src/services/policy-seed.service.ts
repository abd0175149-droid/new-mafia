/** يُزرع مرّةً. لا يُحدِّث نسخةً منشورةً أبداً. */
export async function seedPolicies(): Promise<void> {
  const db = getDB();
  if (!db) return;

  const docs = [
    { kind: 'privacy', version: PRIVACY_VERSION, title: 'سياسة الخصوصيّة', body: PRIVACY_BODY },
    { kind: 'terms', version: TERMS_VERSION, title: 'شروط الاستخدام', body: TERMS_BODY },
  ];

  for (const d of docs) {
    const [exists] = await db.select({ id: policyVersions.id })
      .from(policyVersions)
      .where(and(eq(policyVersions.kind, d.kind), eq(policyVersions.version, d.version)))
      .limit(1);
    if (exists) continue;
    await db.insert(policyVersions).values({
      kind: d.kind, version: d.version, lang: 'ar',
      title: d.title, body: d.body,
      changeSummary: 'النسخة الأولى',
      requiresReconsent: true,
      publishedAt: new Date(),
    } as any);
    console.log(`📜 نُشرت ${d.title} — النسخة ${d.version}`);
  }
}
