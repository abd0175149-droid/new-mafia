const empty = (v: any) =>
  v === null || v === undefined || v === '' ||
  (Array.isArray(v) && v.length === 0) ||
  (typeof v === 'object' && !Array.isArray(v) && Object.keys(v).length === 0);

async function main() {
  const force = process.argv.includes('--force');
  const onlyArg = process.argv.find(a => a.startsWith('--only='));
  const only = onlyArg
    ? new Set(onlyArg.slice(7).split(',').map(s => s.trim().toUpperCase()).filter(Boolean))
    : null;
  // 🔴 دورٌ محدَّدٌ يُكتب فوقه دائماً: طالبُه يعرف ما يطلب، وإلّا كان النداءُ بلا أثر
  const forceRow = (id: string) => force || (!!only && only.has(id));
  await connectDB();
  const db = getDB();
  if (!db) throw new Error('لا اتّصال بقاعدة البيانات');

  const rows = await db.select().from(roleDefinitions);
  let written = 0, skipped = 0, missing: string[] = [];

  for (const row of rows as any[]) {
    const s = SEED[row.id];
    if (!s) { missing.push(row.id); continue; }
    if (only && !only.has(row.id)) { skipped++; continue; }
    const force = forceRow(row.id);

    const patch: Record<string, any> = {};
    const put = (col: string, cur: any, val: any) => {
      if (val === undefined) return;
      if (force || empty(cur)) patch[col] = val;
    };
    put('oneLiner', row.oneLiner, s.oneLiner);
    put('howItWorks', row.howItWorks, s.howItWorks);
    put('extraLimits', row.extraLimits, s.extraLimits ?? []);
    put('interactsWith', row.interactsWith, s.interactsWith ?? []);
    put('tips', row.tips, s.tips ?? []);
    put('phaseNotes', row.phaseNotes, s.phaseNotes);
    // 🔴 المصفوفةُ الفارغة قيمةٌ صادقة هنا («لا دورَ لك في أيّ مرحلة»)، فلا
    //    تُعامَل معاملةَ الفارغ: نكتبها إن كان العمود null فقط.
    if (force || row.actsInPhases === null || row.actsInPhases === undefined) {
      patch.actsInPhases = s.actsInPhases;
    }

    if (Object.keys(patch).length === 0) { skipped++; continue; }
    await db.update(roleDefinitions)
      .set({ ...patch, updatedAt: new Date() } as any)
      .where(eq(roleDefinitions.id, row.id));
    written++;
    console.log(`  ✅ ${row.id.padEnd(17)} ← ${Object.keys(patch).join(', ')}`);
  }

  console.log(`\nكُتب: ${written} · تُرك كما هو: ${skipped}`);
  if (missing.length) console.log(`⚠️  بلا بذرة (يُكتب محتواها من لوحة الإدارة): ${missing.join(', ')}`);
  process.exit(0);
}

main().catch((e) => { console.error('❌', e.message); process.exit(1); });
