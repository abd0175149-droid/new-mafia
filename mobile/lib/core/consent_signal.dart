// الخلل الذي وُجد: بوّابة الموافقة كانت تُفحص عند إقلاع التطبيق وحده. لاعبٌ أنشأ حسابه
// (أو دخل) من داخل التطبيق بعد الإقلاع لم تُفحص حالته قطّ، فلا بوّابة تظهر — والخادم
// يرفض انضمامه وحجزه بـCONSENT_REQUIRED. يقرأ «يلزم قبول الشروط» ولا يجد أين يقبل.
//
// العلاج في موضعين:
//   ١. تغيّر الجلسة (دخول · تسجيل · خروج) يُعيد الفحص — في app.dart.
//   ٢. أيّ ردٍّ من الخادم يحمل CONSENT_REQUIRED (REST أو سوكِت) يطلب الفحص من هنا،
//      فتظهر البوّابة في اللحظة التي رُفض فيها الفعل ولو فات الفحصُ الأوّل لأيّ سبب.
//
// ملفٌّ صغير بلا تبعيّات كي يستورده عميل REST والسوكِت بلا دورة استيراد مع الواجهة.
// ══════════════════════════════════════════════════════

class ConsentSignal {
  ConsentSignal._();

  /// يزيد واحداً عند كلّ طلب فحص — من يستمع يُعيد قراءة الحالة من الخادم.
  static final ValueNotifier<int> recheck = ValueNotifier<int>(0);

  static void request() => recheck.value++;

  /// ردّ الخادم يقول إنّ الموافقة ناقصة؟
  static bool isConsentRequired(Object? code) => code == 'CONSENT_REQUIRED';
}
